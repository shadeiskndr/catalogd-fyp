import { Database } from "bun:sqlite";
import { readFileSync, writeFileSync } from "node:fs";
import { parseArgs } from "node:util";
import { $ } from "bun";

const DEFAULT_DB = "/home/siskandar/Downloads/p/videogames_with_embeddings.db";

const { values } = parseArgs({
  args: Bun.argv.slice(2),
  options: {
    db: { type: "string", default: DEFAULT_DB },
    queries: { type: "string", default: "evaluation/queries.json" },
    out: { type: "string", default: "evaluation/03-debug-search.md" },
    purpose: { type: "string" },
    limit: { type: "string", default: "10" },
    label: { type: "string", default: "" },
    modality: { type: "string" },
  },
});

type Query = { query: string; expect: string[] };
type DebugHit = { rawgId: number; score: number; name: string | null };
type DebugSearchResult = {
  query: string;
  purpose: string;
  embedMs: number;
  searchMs: number;
  hits: DebugHit[];
};

const db = new Database(values.db ?? DEFAULT_DB, { readonly: true });
const nameStmt = db.query("SELECT name, slug FROM games WHERE id = ?");
const queries = JSON.parse(readFileSync(values.queries ?? "", "utf8")) as Query[];
const limit = Number.parseInt(values.limit ?? "10", 10);

const sections: string[] = [];
const embedTimes: number[] = [];
const searchTimes: number[] = [];
let hitsAt1 = 0;
let hitsAt10 = 0;

for (const item of queries) {
  const args: Record<string, unknown> = { query: item.query, limit };
  if (values.purpose !== undefined) args["purpose"] = values.purpose;
  if (values.modality !== undefined) args["modality"] = values.modality;
  const raw = await $`bunx convex run rag:debugSearch ${JSON.stringify(args)}`.quiet().text();
  const result = JSON.parse(raw.slice(raw.indexOf("{"))) as DebugSearchResult;
  embedTimes.push(result.embedMs);
  searchTimes.push(result.searchMs);
  const rows = result.hits.map((hit, index) => {
    const corpus = nameStmt.get(hit.rawgId) as { name: string; slug: string } | null;
    const slug = corpus?.slug ?? "";
    const name = hit.name ?? corpus?.name ?? `rawgId ${hit.rawgId}`;
    const expected = item.expect.includes(slug);
    if (expected && index === 0) hitsAt1 += 1;
    return { rank: index + 1, name, slug, score: hit.score, expected };
  });
  if (rows.some((row) => row.expected)) hitsAt10 += 1;
  sections.push(
    `### ${item.query}\n\nExpected: ${item.expect.map((slug) => `\`${slug}\``).join(", ")}  \nEmbed ${result.embedMs}ms, vector search ${result.searchMs}ms\n\n| # | Game | Score | Expected |\n| --- | --- | --- | --- |\n${rows
      .map(
        (row) =>
          `| ${row.rank} | ${row.name} (\`${row.slug}\`) | ${row.score.toFixed(3)} | ${row.expected ? "yes" : ""} |`
      )
      .join("\n")}\n`
  );
  console.log(
    `${item.query} -> ${rows.filter((row) => row.expected).length} expected in top ${limit}`
  );
}

function percentile(valuesIn: number[], p: number): number {
  const sorted = [...valuesIn].sort((a, b) => a - b);
  return sorted[Math.min(sorted.length - 1, Math.floor(p * sorted.length))] ?? 0;
}

const purpose = values.purpose ?? "GENERIC_RETRIEVAL";
const header = `# debugSearch over ${queries.length} fixed queries${values.label ? ` (${values.label})` : ""}

Generated by \`bun run scripts/rag-eval.ts\` on ${new Date().toISOString().slice(0, 10)}. Query purpose: \`${purpose}\`. Searched modality: \`${values.modality ?? "text"}\`. Names come from the \`games\` table when the hit is warm and from the local corpus otherwise; the deployment never stores corpus metadata.

| Metric | Value |
| --- | --- |
| Queries with an expected game at rank 1 | ${hitsAt1} / ${queries.length} |
| Queries with an expected game in the top ${limit} | ${hitsAt10} / ${queries.length} |
| Embed latency p50 / p95 | ${percentile(embedTimes, 0.5)}ms / ${percentile(embedTimes, 0.95)}ms |
| Vector search latency p50 / p95 | ${percentile(searchTimes, 0.5)}ms / ${percentile(searchTimes, 0.95)}ms |

`;
writeFileSync(values.out ?? "", header + sections.join("\n"));
console.log(
  `\nrank1=${hitsAt1}/${queries.length} top${limit}=${hitsAt10}/${queries.length} -> ${values.out}`
);
